"""
Generation by NGrams starter
"""

# pylint:disable=too-many-locals, unused-import, unused-variable

from lab_3_generate_by_ngrams.main import (
    BeamSearchTextGenerator,
    GreedyTextGenerator,
    NGramLanguageModel,
    TextProcessor,
)


def main() -> None:
    """
    Launches an implementation.

    In any case returns, None is returned
    """
    with open(
        "./lab_3_generate_by_ngrams/assets/Harry_Potter.txt", "r", encoding="utf-8"
    ) as text_file:
        text = text_file.read()

    processor = TextProcessor("_")
    encoded = processor.encode(text)
    assert encoded, "Text can not be encoded"

    print(f"Encoded example: {encoded[:200]}")

    decoded = processor.decode(encoded)
    assert decoded, "Text can not be decoded"

    print(f"Decoded example: {decoded[:200]}")

    model = NGramLanguageModel(encoded, 7)
    built = model.build()
    assert built, "The result of method build is None"

    print(f"The result of method build: {built}")

    generator = GreedyTextGenerator(model, processor)
    generated_text = generator.run("Vernon", 51)
    assert generated_text, "Generated text is None"

    print(f"The result of greedy generator's work: {generated_text}")

    beam_generator = BeamSearchTextGenerator(model, processor, beam_width=3)
    result = beam_generator.run("Vernon", 56)
    print(f"The text generated by beam search generator: {result}")

    assert result


if __name__ == "__main__":
    main()
